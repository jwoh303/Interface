SELECT /*+ S603 UI  가동일보 호스트별현황 StatHostVO 황용길 */
  code ,
  syst ,
  Syst.HOST_NAME name ,
  src ,
  tot ,
  t00 ,
  t01 ,
  t02 ,
  t03 ,
  t04 ,
  t05 ,
  t06 ,
  t07 ,
  t08 ,
  t09 ,
  t10 ,
  t11 ,
  t12 ,
  t13 ,
  t14 ,
  t15 ,
  t16 ,
  t17 ,
  t18 ,
  t19 ,
  t20 ,
  t21 ,
  t22 ,
  t23
FROM (
    SELECT DECODE(GROUPING(SERVICE_INST_ID), 1, '합계', NVL(SERVICE_INST_ID, 'OTHER')) code ,
      DECODE(SEND_RECEIVE_CODE, 'S', '송신', 'R', '수신', SEND_RECEIVE_CODE) src ,
      DECODE(SERVICE_INST_ID , '' , '' , MIN(EAI_SYSTEM_ID)) syst ,
      SUM(DATA_COUNT ) tot ,
      SUM(TIME_COUNT0 ) t00,
      SUM(TIME_COUNT1 ) t01,
      SUM(TIME_COUNT2 ) t02 ,
      SUM(TIME_COUNT3 ) t03,
      SUM(TIME_COUNT4 ) t04,
      SUM(TIME_COUNT5 ) t05 ,
      SUM(TIME_COUNT6 ) t06,
      SUM(TIME_COUNT7 ) t07,
      SUM(TIME_COUNT8 ) t08 ,
      SUM(TIME_COUNT9 ) t09,
      SUM(TIME_COUNT10) t10,
      SUM(TIME_COUNT11) t11 ,
      SUM(TIME_COUNT12) t12,
      SUM(TIME_COUNT13) t13,
      SUM(TIME_COUNT14) t14 ,
      SUM(TIME_COUNT15) t15,
      SUM(TIME_COUNT16) t16,
      SUM(TIME_COUNT17) t17 ,
      SUM(TIME_COUNT18) t18,
      SUM(TIME_COUNT19) t19,
      SUM(TIME_COUNT20) t20 ,
      SUM(TIME_COUNT21) t21,
      SUM(TIME_COUNT22) t22,
      SUM(TIME_COUNT23) t23
    FROM TB_S60_SUMM010
    WHERE EAI_SEND_DATE LIKE REPLACE(? , '-', '') || '%'
    GROUP BY CUBE(SERVICE_INST_ID), SEND_RECEIVE_CODE ) Summ ,
  TB_S60_SYST020 Syst
WHERE Summ.syst = Syst.EAI_SYSTEM_ID (+)
ORDER BY code, src
