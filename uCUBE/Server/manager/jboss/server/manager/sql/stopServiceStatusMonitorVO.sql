SELECT DISTINCT EAI_SYSTEM_ID,
  SERVICE_NAME,
  SERVICE_LINK_NAME,
  (
    SELECT QUEUE_DESCRIPTION
    FROM TB_S60_QNAM010
    WHERE SERVICE_LINK_NAME = LOCAL_QUEUE_NAME) DESCRIPTION,
  BL_STATUS,
  TO_CHAR(LAST_UPDATE_TIMESTAMP, 'YYYY/MM/DD HH24:MI:SS'),
  STATUS_SEQ_ID,
  DESCRIPTION,
  TO_CHAR(DATA_ACCRUAL_TIME, 'YYYY/MM/DD HH24:MI:SS') DATA_ACCRUAL_TIME
FROM TB_S60_STAT020
WHERE LAST_UPDATE_TIMESTAMP IS NOT NULL
  AND EAI_SYSTEM_ID LIKE CONCAT(? , '%')
  AND SERVICE_NAME LIKE CONCAT(? , '%')
  AND SERVICE_LINK_NAME LIKE CONCAT(? , '%')
  AND (SYSDATE - LAST_UPDATE_TIMESTAMP > INTERVAL '0 00:01:40.0000' DAY TO SECOND OR BL_STATUS = 'ERROR')
  ORDER BY BL_STATUS, SERVICE_NAME, EAI_SYSTEM_ID

