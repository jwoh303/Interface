SELECT EAI_INTERFACE_ID,
  SEND_EAI_SYSTEM_ID,
  SEND_APP_NAME,
  SEND_LINK_NAME,
  (
    SELECT BL_STATUS
    FROM TB_S60_STAT020
    WHERE EAI_SYSTEM_ID = IFMG.SEND_EAI_SYSTEM_ID
      AND SERVICE_NAME = IFMG.SEND_APP_NAME
      AND SERVICE_LINK_NAME = IFMG.SEND_LINK_NAME) SEND_STATUS,
  (
    SELECT TO_CHAR(LAST_UPDATE_TIMESTAMP,'yyyy/mm/dd hh24:mi:ss')
    FROM TB_S60_STAT020
    WHERE EAI_SYSTEM_ID = IFMG.SEND_EAI_SYSTEM_ID
      AND SERVICE_NAME = IFMG.SEND_APP_NAME
      AND SERVICE_LINK_NAME = IFMG.SEND_LINK_NAME) SEND_LTIME,
  RECV_EAI_SYSTEM_ID,
  RECV_APP_NAME,
  RECV_LINK_NAME,
  (
    SELECT BL_STATUS
    FROM TB_S60_STAT020
    WHERE EAI_SYSTEM_ID = IFMG.RECV_EAI_SYSTEM_ID
      AND SERVICE_NAME = IFMG.RECV_APP_NAME
      AND SERVICE_LINK_NAME = IFMG.RECV_LINK_NAME) RECV_STATUS,
  (
    SELECT TO_CHAR(LAST_UPDATE_TIMESTAMP,'yyyy/mm/dd hh24:mi:ss')
    FROM TB_S60_STAT020
    WHERE EAI_SYSTEM_ID = IFMG.RECV_EAI_SYSTEM_ID
      AND SERVICE_NAME = IFMG.RECV_APP_NAME
      AND SERVICE_LINK_NAME = IFMG.RECV_LINK_NAME) RECV_LTIME
FROM TB_S60_IFMG020 IFMG
WHERE INTERFACE_SECTION LIKE CONCAT(?, '%')
  AND EAI_INTERFACE_ID LIKE CONCAT(? , '%')
  AND SEND_EAI_SYSTEM_ID LIKE CONCAT(? , '%')
  AND RECV_EAI_SYSTEM_ID LIKE CONCAT(? , '%')
