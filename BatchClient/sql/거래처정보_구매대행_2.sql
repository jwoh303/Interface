SELECT 
       'KA'||TO_CHAR(SYSDATE, 'YYYYMMDD')||'0004' AS IF_ID, ROWNUM AS IF_SEQ,
       K.*
  FROM (
SELECT 
  'KA' AS IF_SYSTEM,
  '1000' CD_COMPANY,
  REPLACE(A.IRS_NO, '-' ,'') CD_PARTNER,
  A.COM_NAME_LOC LN_PARTNER,
  REPLACE(A.IRS_NO, '-' ,'') NO_COMPANY,
  A.COM_NAME_LOC SN_PARTNER,
  '001' FG_PARTNER,
  CASE
    WHEN A.BUSINESS_COND = 'S' AND (SELECT COUNT(*) FROM ICOMCMPY WHERE IRS_NO = A.IRS_NO AND COM_CODE != A.COM_CODE ) = 0 THEN '001'
    WHEN A.BUSINESS_COND = 'B' AND (SELECT COUNT(*) FROM ICOMCMPY WHERE IRS_NO = A.IRS_NO AND COM_CODE != A.COM_CODE ) = 0 THEN '002'
    WHEN (SELECT COUNT(*) FROM ICOMCMPY WHERE IRS_NO = A.IRS_NO AND COM_CODE != A.COM_CODE ) > 0 THEN '003'
    ELSE '004'
  END CLS_PARTNER,
  '' NO_MERCHANT,
  NVL(TX06.TEXT1, '110020') CD_DEPT,
  NVL(TX06.TEXT1, '110020') CD_CC,
  A.CEO_NAME_LOC NM_CEO,
  REPLACE(A.ZIP_CODE,'-','') NO_POST1,
  NVL(A.ADDRESS_LOC1, A.ADDRESS_LOC) DC_ADS1_H,
  A.ADDRESS_LOC2 DC_ADS1_D,
  A.TEL_NO NO_TEL1,
  A.FAX_NO NO_FAX1,
  A.INDUSTRY_TYPE TP_JOB,
  A.BUSINESS_ITEMS CLS_JOB,
  '' CD_EMP_PARTNER,
  '' NO_HPEMP_PARTNER,
  '' E_MAIL,
  '' NO_TEL,
  '' NO_FAX,
  'Y' YN_JEONJA,
  '11' CD_TAXTYPE,
  '001' CD_CON,
  '' DT_CLOSE,
  '' NM_TEXT,
  '000' FG_PAYBILL,
  '000' FG_BILL,
  'Y' USE_YN
  FROM ICOMCMPY A
       LEFT OUTER JOIN ICOMLUSR B ON (1 = 1
         AND B.USER_ID = A.CONFIRM_USER_ID
       )
       LEFT OUTER JOIN ICOMCOD1 TX06 ON (1 = 1
         AND TX06.TYPE = 'TX06'
         AND TX06.CODE = B.DEPARTMENT
       )
 WHERE A.STATUS IN ('C','R')
   AND A.IRS_NO IS NOT NULL
   AND A.IRS_NO != '107-81-85880'
) K
;