SELECT 
       'KA'||TO_CHAR(SYSDATE, 'YYYYMMDD')||'0006' AS IF_ID, ROWNUM AS IF_SEQ,
       K.*
  FROM (
SELECT 
       'KA' AS IF_SYSTEM,
       '1000' CD_COMPANY,
       REPLACE(B.IRS_NO,'-','') CD_PARTNER,
       REPLACE(B.IRS_NO,'-','') NO_COMPANY,
--       A.BANK_ACCOUNT_NO
       '110201128484' NO_DEPOSIT,
       A.BANK_CD CD_BANK,
       A.DEPOSITOR NM_DEPOSIT,
       'N' USE_YN,
       'Y' HELP_USE,
       '' DC_RMK,
       (ROW_NUMBER() OVER(PARTITION BY A.BANK_ACCOUNT_NO ORDER BY A.CONFIRM_ADD_DATE) ) + 10 CD_DEPOSITNO
  FROM ACNTSUPL A
       INNER JOIN ICOMCMPY B ON (1 = 1
         AND B.COM_CODE = A.SUPPLIER
         AND B.IRS_NO not in ( '107-81-85880' , '671-01-11144' )
       )
) K       
;