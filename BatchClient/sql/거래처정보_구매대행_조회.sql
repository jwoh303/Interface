
SELECT CD_PARTNER, CD_COMPANY, LN_PARTNER, NO_COMPANY, SN_PARTNER, FG_PARTNER, CLS_PARTNER, CD_DEPT, CD_CC, NM_CEO, NO_POST1, DC_ADS1_H, DC_ADS1_D, NO_TEL1, NO_FAX1, TP_JOB, CLS_JOB, YN_JEONJA, CD_TAXTYPE, CD_CON, DT_CLOSE, NM_TEXT, USE_YN
FROM (
SELECT 
REPLACE(IRS_NO,'-','') CD_PARTNER
, ROW_NUMBER() OVER(PARTITION BY IRS_NO ORDER BY A.ADD_DATE) AS RNUM
, '1000' CD_COMPANY
, SUBSTRB(COM_NAME_LOC, 1, 50) LN_PARTNER
, REPLACE(IRS_NO,'-','') NO_COMPANY
, SUBSTRB(COM_NAME_LOC, 1, 50) SN_PARTNER
, '001' FG_PARTNER
, CASE
   WHEN A.BUSINESS_COND = 'B' THEN '001'
   ELSE '002'
  END CLS_PARTNER
, '' CD_DEPT
, '' CD_CC
, CEO_NAME_LOC NM_CEO
, A.ZIP_CODE NO_POST1
, NVL(A.ADDRESS_LOC1, A.ADDRESS_LOC) DC_ADS1_H
, A.ADDRESS_LOC2 DC_ADS1_D
, A.TEL_NO NO_TEL1
, A.FAX_NO NO_FAX1
, A.INDUSTRY_TYPE TP_JOB
, A.BUSINESS_ITEMS CLS_JOB
, 'Y' YN_JEONJA
, '11' CD_TAXTYPE
, '001' CD_CON
, '' DT_CLOSE
, '' NM_TEXT
, 'Y' USE_YN
  FROM ICOMCMPY A
 WHERE STATUS IN ('C','R')
   AND EXISTS (
     SELECT 'X' FROM ICOMPOHD
      WHERE ( BUYER = A.COM_CODE OR AGENT = A.COM_CODE )
        AND STATUS != 'D'
        AND PO_CREATE_DATE >= '20210101'
   )
)
WHERE RNUM = 1