SELECT CSTMR_ID "구매사코드"
     , GETALANCINFO(CSTMR_ID, 'ALANC_NM') "구매사명"
     , GETALANCINFO(CSTMR_ID, 'BIZMN_REGST_NO') "구매사 사업자번호"
     , YYMON "마감년월"
     , SUM(SLS) "매출금액"
     , SUM(PRCHS) "매입금액"
  FROM (SELECT CSTMR_ID, CLSN_YYMON YYMON, SLS_AMT SLS, 0 PRCHS
          FROM KEPMPCL02
         WHERE CLSN_YYMON = '202109'
           AND BIZ_CLSS_CD = 'C001'
           AND SLS_CNFRM_CHK = 'Y'
           AND USE_CHK = 'Y'
         UNION ALL
        SELECT CSTMR_ID, ACCNT_YYMON YYMON, 0 SLS, DLVRY_AMT PRCHS
          FROM KEPCMRP05
         WHERE ACCNT_YYMON = '202109'
           AND BIZ_CLSS_CD = 'C001')
 GROUP BY CSTMR_ID, YYMON
HAVING SUM(SLS) > 0 OR SUM(PRCHS) > 0
 ORDER BY 3