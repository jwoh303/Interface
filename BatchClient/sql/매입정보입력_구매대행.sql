SELECT 
       'KA'||TO_CHAR(SYSDATE, 'YYYYMMDD')||'0002' AS IF_ID, ROWNUM AS IF_SEQ,
       K.*
  FROM (
select 
		'KA' IF_SYSTEM, '1000' CD_COMPANY,	A.TAX_BILL_NO ROW_ID,	ROW_NUMBER() OVER(PARTITION BY A.TAX_BILL_NO ORDER BY A.ADD_DATE, A.ADD_TIME) SEQ,	
		'1010' CD_EPCODE,	'1000' CD_PC,	'110020' CD_WDEPT,	A.ISSUE_DATE DT_ACCT,	TX02.TEXT8 CD_EVID,
		'' DT_START,	'' DT_END,	SUBSTRB(A.REMARK_DESCRIPTION || A.REMARK_SPECIFICATION,1,100) NM_NOTE, A.SUPP_PRICE AM_TAXSTD,	NVL(A.TAX_PRICE,0) AM_ADDTAX,
		TX01.TEXT1 CD_BIZAREA,	TX06.TEXT1 CD_CC,	TX06.TEXT1 CD_DEPT,	REPLACE(A.SEND_USER_ID, 'KEP', '') CD_EMPLOY,	TRIM(REPLACE(A.IRS_NO,'-','')) CD_PARTNER,
		TRIM(REPLACE(A.IRS_NO,'-','')) NO_COMPANY,	A.BUYER_CODE CD_UMNG1,	TX06.TEXT1 CD_MNGD1,	TX06.TEXT2 NM_MNGD1,	TRIM(REPLACE(A.IRS_NO,'-','')) CD_MNGD2,
		A.IRS_NAME NM_MNGD2,	'' CD_MNGD3,	'' NM_MNGD3,	'' CD_MNGD4,	'' NM_MNGD4,
		'' CD_MNGD5,	A.TAX_PRICE NM_MNGD5,	'' CD_MNGD6,	'' NM_MNGD6,	'' CD_MNGD7,
		'' NM_MNGD7,	A.BUYER_CODE CD_MNGD8,	A.IRS_NAME NM_MNGD8,	'' CD_MNGD9,	A.TAX_BILL_NO NM_MNGD9,
		'KA' CD_MNGD10,	'구매대행' NM_MNGD10,	 '000' CD_EXCH,	'' RT_EXCH,	'' AM_EX,
		'' ST_MUTUAL,	'' NO_TO,	'' DT_SHIPPING,	TX02.TEXT7 TP_EVIDENCE
  from KEPTAPDT A
       INNER JOIN ICOMCOD1 TX01 ON (1 = 1
         AND TX01.TYPE = 'TX01'
         AND TX01.CODE = A.KEP_IRS
       )
       INNER JOIN ICOMCOD1 TX02 ON (1 = 1
         AND TX02.TYPE = 'TX02'
         AND TX02.CODE = A.TAX_TYPE
       )
       INNER JOIN ICOMCOD1 TX06 ON (1 = 1
         AND TX06.TYPE = 'TX06'
         AND TX06.CODE = A.DEPT_CODE
       )
 WHERE A.ISSUE_DATE LIKE '202107%'
 ORDER BY ROW_ID, SEQ
 )  K