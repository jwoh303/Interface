/**********************************************
 * 표준DB 구매정보코드 — 화면·양식 표기는 순번(00001)만 쓰고, 키는 전체코드(상품정보코드-순번)를 쓴다.
 * 양식에서 읽은 순번을 같은 행의 상품정보코드와 합쳐 키로 되돌리는 자리다.
 **********************************************/

/* 순번(00001)이든 예전 양식의 전체코드(M000012345-00001)든 받아 키로 되돌린다.
 * 순번만 왔는데 상품정보코드가 비었으면 되돌릴 수 없다 - 빈 문자열을 주고 검증이 잡게 둔다. */
function mdcmBuyInfoFull(catlgId, v) {
	var s = $.trim((v == null) ? "" : ("" + v));
	var c = $.trim((catlgId == null) ? "" : ("" + catlgId));
	if (s == "") { return ""; }
	if (s.indexOf("-") > -1) { return s; }
	if (c == "") { return ""; }
	if (/^\d+$/.test(s)) { while (s.length < 5) { s = "0" + s; } }
	return c + "-" + s;
}
